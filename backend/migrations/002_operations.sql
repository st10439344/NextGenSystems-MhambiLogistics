-- 002: warehouses, drivers, vehicles, quotations, shipments and delivery workflow
CREATE TABLE warehouses (
  id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code    VARCHAR(12) NOT NULL UNIQUE,
  name    VARCHAR(120) NOT NULL,
  city    VARCHAR(80) NOT NULL,
  address VARCHAR(255),
  status  VARCHAR(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive'))
);

CREATE TABLE drivers (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        BIGINT UNIQUE REFERENCES users(id) ON DELETE SET NULL,
  licence_number VARCHAR(30) NOT NULL UNIQUE,
  licence_code   VARCHAR(6) NOT NULL DEFAULT 'EC',
  phone          VARCHAR(30),
  status         VARCHAR(12) NOT NULL DEFAULT 'available' CHECK (status IN ('available','off_duty','suspended'))
);

CREATE TABLE vehicles (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  registration      VARCHAR(20) NOT NULL UNIQUE,
  make_model        VARCHAR(80) NOT NULL,
  type              VARCHAR(60) NOT NULL,
  capacity_kg       INTEGER NOT NULL CHECK (capacity_kg > 0),
  status            VARCHAR(14) NOT NULL DEFAULT 'available'
                    CHECK (status IN ('available','assigned','on_route','maintenance','idle','retired')),
  mileage_km        INTEGER NOT NULL DEFAULT 0 CHECK (mileage_km >= 0),
  last_service_date DATE,
  next_service_date DATE,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE SEQUENCE quotation_ref_seq START 1001;
CREATE SEQUENCE tracking_ref_seq START 10001;

CREATE TABLE quotations (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference          VARCHAR(20) NOT NULL UNIQUE,
  company_id         BIGINT NOT NULL REFERENCES companies(id),
  requested_by       BIGINT REFERENCES users(id) ON DELETE SET NULL,
  origin             VARCHAR(160) NOT NULL,
  destination        VARCHAR(160) NOT NULL,
  cargo_description  VARCHAR(300) NOT NULL,
  weight_kg          NUMERIC(10,2) NOT NULL CHECK (weight_kg > 0),
  service_type       VARCHAR(30) NOT NULL DEFAULT 'standard' CHECK (service_type IN ('standard','express','refrigerated','bulk','hazardous')),
  preferred_date     DATE,
  status             VARCHAR(12) NOT NULL DEFAULT 'submitted'
                     CHECK (status IN ('submitted','in_review','quoted','accepted','rejected','declined','converted')),
  quoted_amount      NUMERIC(14,2) CHECK (quoted_amount IS NULL OR quoted_amount >= 0),
  staff_notes        TEXT,
  processed_by       BIGINT REFERENCES users(id) ON DELETE SET NULL,
  processed_at       TIMESTAMPTZ,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_quotations_company ON quotations (company_id);
CREATE INDEX idx_quotations_status ON quotations (status);

CREATE TABLE shipments (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracking_ref      VARCHAR(20) NOT NULL UNIQUE,
  quotation_id      BIGINT UNIQUE REFERENCES quotations(id) ON DELETE SET NULL,
  company_id        BIGINT NOT NULL REFERENCES companies(id),
  warehouse_id      BIGINT REFERENCES warehouses(id) ON DELETE SET NULL,
  origin            VARCHAR(160) NOT NULL,
  destination       VARCHAR(160) NOT NULL,
  cargo_description VARCHAR(300) NOT NULL,
  weight_kg         NUMERIC(10,2) NOT NULL CHECK (weight_kg > 0),
  priority          VARCHAR(10) NOT NULL DEFAULT 'normal' CHECK (priority IN ('low','normal','high','urgent')),
  status            VARCHAR(12) NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending','assigned','collected','in_transit','delivered','failed','cancelled')),
  scheduled_date    DATE,
  eta               DATE,
  created_by        BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  delivered_at      TIMESTAMPTZ
);
CREATE INDEX idx_shipments_company ON shipments (company_id);
CREATE INDEX idx_shipments_status ON shipments (status);

CREATE TABLE shipment_status_history (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id BIGINT NOT NULL REFERENCES shipments(id) ON DELETE CASCADE,
  status      VARCHAR(12) NOT NULL,
  note        VARCHAR(300),
  location    VARCHAR(160),
  changed_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_ssh_shipment ON shipment_status_history (shipment_id, created_at);

CREATE TABLE delivery_assignments (
  id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id        BIGINT NOT NULL REFERENCES shipments(id) ON DELETE CASCADE,
  driver_id          BIGINT NOT NULL REFERENCES drivers(id),
  vehicle_id         BIGINT NOT NULL REFERENCES vehicles(id),
  assigned_by        BIGINT REFERENCES users(id) ON DELETE SET NULL,
  scheduled_pickup   TIMESTAMPTZ,
  scheduled_delivery TIMESTAMPTZ,
  status             VARCHAR(12) NOT NULL DEFAULT 'assigned' CHECK (status IN ('assigned','active','completed','cancelled')),
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (scheduled_delivery IS NULL OR scheduled_pickup IS NULL OR scheduled_delivery >= scheduled_pickup)
);
-- Database-level protection against double booking
CREATE UNIQUE INDEX uq_assign_live_shipment ON delivery_assignments (shipment_id) WHERE status IN ('assigned','active');
CREATE UNIQUE INDEX uq_assign_live_vehicle  ON delivery_assignments (vehicle_id)  WHERE status IN ('assigned','active');
CREATE UNIQUE INDEX uq_assign_active_driver ON delivery_assignments (driver_id)   WHERE status = 'active';
CREATE INDEX idx_assign_driver ON delivery_assignments (driver_id);

CREATE TABLE proof_of_delivery (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id    BIGINT NOT NULL UNIQUE REFERENCES shipments(id) ON DELETE CASCADE,
  driver_id      BIGINT REFERENCES drivers(id) ON DELETE SET NULL,
  recipient_name VARCHAR(120) NOT NULL,
  note           VARCHAR(300),
  latitude       NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90),
  longitude      NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180),
  delivered_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE incidents (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  driver_id   BIGINT NOT NULL REFERENCES drivers(id),
  shipment_id BIGINT REFERENCES shipments(id) ON DELETE SET NULL,
  vehicle_id  BIGINT REFERENCES vehicles(id) ON DELETE SET NULL,
  type        VARCHAR(30) NOT NULL CHECK (type IN ('breakdown','accident','delay','damage','theft','other')),
  severity    VARCHAR(10) NOT NULL DEFAULT 'low' CHECK (severity IN ('low','medium','high')),
  description TEXT NOT NULL,
  status      VARCHAR(14) NOT NULL DEFAULT 'open' CHECK (status IN ('open','investigating','resolved')),
  reported_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_incidents_driver ON incidents (driver_id);
