CREATE TABLE permissions (
  id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR(60) NOT NULL UNIQUE,
  description TEXT NOT NULL
);

CREATE TABLE role_permissions (
  role_id       SMALLINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  permission_id SMALLINT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
  PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE companies (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_code         VARCHAR(20) NOT NULL UNIQUE,
  name                VARCHAR(160) NOT NULL,
  registration_number VARCHAR(40),
  vat_number          VARCHAR(20),
  industry            VARCHAR(80),
  address             VARCHAR(255),
  city                VARCHAR(80),
  province            VARCHAR(60),
  postal_code         VARCHAR(10),
  phone               VARCHAR(30),
  email               VARCHAR(255),
  status              VARCHAR(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_companies_name ON companies (lower(name));

CREATE TABLE users (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email                VARCHAR(255) NOT NULL,
  password_hash        TEXT,
  full_name            VARCHAR(120) NOT NULL,
  phone                VARCHAR(30),
  company_id           BIGINT REFERENCES companies(id) ON DELETE SET NULL,
  status               VARCHAR(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  google_sub           VARCHAR(64) UNIQUE,
  must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
  last_login_at        TIMESTAMPTZ,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (password_hash IS NOT NULL OR google_sub IS NOT NULL)
);
CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email));
CREATE INDEX idx_users_company ON users (company_id);

CREATE TABLE user_roles (
  user_id     BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  role_id     SMALLINT NOT NULL REFERENCES roles(id),
  assigned_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  assigned_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_user_roles_role ON user_roles (role_id);

CREATE TABLE refresh_sessions (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash  CHAR(64) NOT NULL UNIQUE,
  expires_at  TIMESTAMPTZ NOT NULL,
  revoked_at  TIMESTAMPTZ,
  replaced_by BIGINT,
  user_agent  VARCHAR(300),
  ip          VARCHAR(64),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_refresh_user ON refresh_sessions (user_id);

CREATE TABLE password_reset_tokens (
  id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash CHAR(64) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at    TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE settings (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT REFERENCES users(id) ON DELETE CASCADE,  -- NULL = system-wide setting
  key        VARCHAR(60) NOT NULL,
  value      JSONB NOT NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_settings_user_key ON settings (user_id, key) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX uq_settings_system_key ON settings (key) WHERE user_id IS NULL;

CREATE TABLE notifications (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title       VARCHAR(160) NOT NULL,
  message     TEXT NOT NULL,
  type        VARCHAR(30) NOT NULL DEFAULT 'info' CHECK (type IN ('info','success','warning','error')),
  entity_type VARCHAR(40),
  entity_id   BIGINT,
  read_at     TIMESTAMPTZ,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notifications_user_unread ON notifications (user_id, read_at);

CREATE TABLE audit_logs (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT REFERENCES users(id) ON DELETE SET NULL,
  action      VARCHAR(60) NOT NULL,
  entity_type VARCHAR(40),
  entity_id   BIGINT,
  details     JSONB,
  ip          VARCHAR(64),
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_created ON audit_logs (created_at DESC);
CREATE INDEX idx_audit_user ON audit_logs (user_id);
