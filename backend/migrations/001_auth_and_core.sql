CREATE TABLE roles (
  id          SMALLINT PRIMARY KEY,
  code        VARCHAR(30) NOT NULL UNIQUE
              CHECK (code IN ('admin','dispatcher','warehouse','fleet','procurement','finance','driver','client')),
  name        VARCHAR(60) NOT NULL,
  description TEXT NOT NULL
);

