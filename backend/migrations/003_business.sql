-- 003: warehouse, fleet operations, procurement, finance, documents, support
CREATE TABLE inventory (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  warehouse_id  BIGINT NOT NULL REFERENCES warehouses(id),
  sku           VARCHAR(30) NOT NULL,
  name          VARCHAR(160) NOT NULL,
  category      VARCHAR(60) NOT NULL,
  unit          VARCHAR(20) NOT NULL DEFAULT 'units',
  quantity      INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
  reorder_level INTEGER NOT NULL DEFAULT 10 CHECK (reorder_level >= 0),
  location      VARCHAR(40),
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (warehouse_id, sku)
);
CREATE INDEX idx_inventory_sku ON inventory (sku);

CREATE TABLE stock_movements (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventory_id BIGINT NOT NULL REFERENCES inventory(id) ON DELETE CASCADE,
  type         VARCHAR(14) NOT NULL CHECK (type IN ('receive','dispatch','transfer_in','transfer_out','adjustment')),
  quantity     INTEGER NOT NULL CHECK (quantity <> 0),   -- signed: positive adds stock, negative removes
  balance_after INTEGER NOT NULL CHECK (balance_after >= 0),
  reference    VARCHAR(60),
  shipment_id  BIGINT REFERENCES shipments(id) ON DELETE SET NULL,
  note         VARCHAR(300),
  performed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_stock_mov_inv ON stock_movements (inventory_id, created_at);

CREATE TABLE stock_transfers (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference         VARCHAR(20) NOT NULL UNIQUE,
  sku               VARCHAR(30) NOT NULL,
  from_warehouse_id BIGINT NOT NULL REFERENCES warehouses(id),
  to_warehouse_id   BIGINT NOT NULL REFERENCES warehouses(id),
  quantity          INTEGER NOT NULL CHECK (quantity > 0),
  note              VARCHAR(300),
  performed_by      BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (from_warehouse_id <> to_warehouse_id)
);

CREATE TABLE suppliers (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         VARCHAR(12) NOT NULL UNIQUE,
  name         VARCHAR(160) NOT NULL,
  category     VARCHAR(60) NOT NULL,
  contact_name VARCHAR(120),
  email        VARCHAR(255),
  phone        VARCHAR(30),
  status       VARCHAR(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','inactive')),
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE maintenance_records (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id     BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
  supplier_id    BIGINT REFERENCES suppliers(id) ON DELETE SET NULL,
  type           VARCHAR(40) NOT NULL,
  description    VARCHAR(300),
  cost           NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (cost >= 0),
  scheduled_date DATE NOT NULL,
  completed_date DATE,
  status         VARCHAR(12) NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled','in_progress','completed','cancelled')),
  created_by     BIGINT REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_maint_vehicle ON maintenance_records (vehicle_id);

CREATE TABLE fuel_transactions (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id     BIGINT NOT NULL REFERENCES vehicles(id) ON DELETE CASCADE,
  driver_id      BIGINT REFERENCES drivers(id) ON DELETE SET NULL,
  litres         NUMERIC(8,2) NOT NULL CHECK (litres > 0),
  cost_per_litre NUMERIC(8,2) NOT NULL CHECK (cost_per_litre > 0),
  total_cost     NUMERIC(12,2) GENERATED ALWAYS AS (round(litres * cost_per_litre, 2)) STORED,
  odometer_km    INTEGER CHECK (odometer_km IS NULL OR odometer_km >= 0),
  station        VARCHAR(80),
  fuelled_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  recorded_by    BIGINT REFERENCES users(id) ON DELETE SET NULL
);
CREATE INDEX idx_fuel_vehicle ON fuel_transactions (vehicle_id);

CREATE SEQUENCE pr_ref_seq START 5001;
CREATE SEQUENCE po_ref_seq START 7001;

CREATE TABLE purchase_requests (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference      VARCHAR(20) NOT NULL UNIQUE,
  requested_by   BIGINT REFERENCES users(id) ON DELETE SET NULL,
  item           VARCHAR(160) NOT NULL,
  quantity       INTEGER NOT NULL CHECK (quantity > 0),
  estimated_cost NUMERIC(14,2) NOT NULL CHECK (estimated_cost >= 0),
  justification  VARCHAR(300),
  status         VARCHAR(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','ordered')),
  decided_by     BIGINT REFERENCES users(id) ON DELETE SET NULL,
  decided_at     TIMESTAMPTZ,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE purchase_orders (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  po_number           VARCHAR(20) NOT NULL UNIQUE,
  supplier_id         BIGINT NOT NULL REFERENCES suppliers(id),
  purchase_request_id BIGINT REFERENCES purchase_requests(id) ON DELETE SET NULL,
  item                VARCHAR(160) NOT NULL,
  quantity            INTEGER NOT NULL CHECK (quantity > 0),
  unit_cost           NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
  status              VARCHAR(12) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','pending','approved','ordered','received','cancelled')),
  created_by          BIGINT REFERENCES users(id) ON DELETE SET NULL,
  ordered_at          TIMESTAMPTZ,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_po_supplier ON purchase_orders (supplier_id);

CREATE TABLE goods_received (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id BIGINT NOT NULL REFERENCES purchase_orders(id),
  warehouse_id      BIGINT NOT NULL REFERENCES warehouses(id),
  inventory_id      BIGINT REFERENCES inventory(id) ON DELETE SET NULL,
  quantity_received INTEGER NOT NULL CHECK (quantity_received > 0),
  note              VARCHAR(300),
  received_by       BIGINT REFERENCES users(id) ON DELETE SET NULL,
  received_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE supplier_invoices (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number    VARCHAR(30) NOT NULL,
  supplier_id       BIGINT NOT NULL REFERENCES suppliers(id),
  purchase_order_id BIGINT REFERENCES purchase_orders(id) ON DELETE SET NULL,
  amount            NUMERIC(14,2) NOT NULL CHECK (amount > 0),
  status            VARCHAR(10) NOT NULL DEFAULT 'unpaid' CHECK (status IN ('unpaid','paid')),
  issue_date        DATE NOT NULL,
  due_date          DATE NOT NULL,
  paid_at           TIMESTAMPTZ,
  UNIQUE (supplier_id, invoice_number),
  CHECK (due_date >= issue_date)
);

CREATE SEQUENCE invoice_ref_seq START 3001;
CREATE SEQUENCE receipt_ref_seq START 9001;

CREATE TABLE invoices (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_number VARCHAR(20) NOT NULL UNIQUE,
  company_id     BIGINT NOT NULL REFERENCES companies(id),
  shipment_id    BIGINT REFERENCES shipments(id) ON DELETE SET NULL,
  description    VARCHAR(300) NOT NULL,
  subtotal       NUMERIC(14,2) NOT NULL CHECK (subtotal >= 0),
  vat_amount     NUMERIC(14,2) NOT NULL CHECK (vat_amount >= 0),
  total          NUMERIC(14,2) NOT NULL CHECK (total >= 0),
  status         VARCHAR(14) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','unpaid','partially_paid','paid','cancelled')),
  issue_date     DATE NOT NULL DEFAULT CURRENT_DATE,
  due_date       DATE NOT NULL,
  created_by     BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (due_date >= issue_date)
);
CREATE INDEX idx_invoices_company ON invoices (company_id);
CREATE INDEX idx_invoices_status ON invoices (status);

CREATE TABLE payments (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  invoice_id  BIGINT NOT NULL REFERENCES invoices(id),
  amount      NUMERIC(14,2) NOT NULL CHECK (amount > 0),
  method      VARCHAR(10) NOT NULL CHECK (method IN ('eft','card','cash','other')),
  reference   VARCHAR(60),
  paid_at     DATE NOT NULL DEFAULT CURRENT_DATE,
  recorded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_payments_invoice ON payments (invoice_id);

CREATE TABLE receipts (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  receipt_number VARCHAR(20) NOT NULL UNIQUE,
  payment_id     BIGINT NOT NULL UNIQUE REFERENCES payments(id) ON DELETE CASCADE,
  issued_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE expenses (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department   VARCHAR(20) NOT NULL CHECK (department IN ('admin','dispatch','warehouse','fleet','procurement','finance')),
  category     VARCHAR(60) NOT NULL,
  description  VARCHAR(300) NOT NULL,
  amount       NUMERIC(14,2) NOT NULL CHECK (amount > 0),
  expense_date DATE NOT NULL,
  status       VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  recorded_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
  decided_by   BIGINT REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE budgets (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department       VARCHAR(20) NOT NULL CHECK (department IN ('admin','dispatch','warehouse','fleet','procurement','finance')),
  period_label     VARCHAR(20) NOT NULL,
  start_date       DATE NOT NULL,
  end_date         DATE NOT NULL,
  allocated_amount NUMERIC(14,2) NOT NULL CHECK (allocated_amount >= 0),
  UNIQUE (department, period_label),
  CHECK (end_date >= start_date)
);

CREATE TABLE documents (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id  BIGINT REFERENCES companies(id) ON DELETE CASCADE,
  shipment_id BIGINT REFERENCES shipments(id) ON DELETE SET NULL,
  invoice_id  BIGINT REFERENCES invoices(id) ON DELETE SET NULL,
  type        VARCHAR(12) NOT NULL CHECK (type IN ('invoice','receipt','pod','quotation','contract','other')),
  title       VARCHAR(160) NOT NULL,
  file_name   VARCHAR(160) NOT NULL,
  mime_type   VARCHAR(80) NOT NULL DEFAULT 'text/html',
  content     TEXT NOT NULL,            -- generated HTML, or base64 for uploads
  is_base64   BOOLEAN NOT NULL DEFAULT FALSE,
  uploaded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_documents_company ON documents (company_id);

CREATE SEQUENCE support_ref_seq START 2001;

CREATE TABLE support_requests (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference    VARCHAR(20) NOT NULL UNIQUE,
  user_id      BIGINT REFERENCES users(id) ON DELETE SET NULL,
  company_id   BIGINT REFERENCES companies(id) ON DELETE SET NULL,
  category     VARCHAR(30) NOT NULL DEFAULT 'general' CHECK (category IN ('general','shipment','billing','technical','account')),
  subject      VARCHAR(160) NOT NULL,
  message      TEXT NOT NULL,
  status       VARCHAR(12) NOT NULL DEFAULT 'open' CHECK (status IN ('open','in_progress','resolved','closed')),
  response     TEXT,
  responded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_support_user ON support_requests (user_id);
